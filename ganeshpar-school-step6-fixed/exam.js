function updateTimer(){const m=String(Math.floor(timeLeft/60)).padStart(2,'0'),s=String(timeLeft%60).padStart(2,'0');$('timer').textContent=`${m}:${s}`}
function finishExam(auto=false){
  clearInterval(timer);
  let score=0; questions.forEach((q,i)=>{if(answers[i]===q[2])score++});
  const studentNumber=sessionStorage.getItem('schoolUser') || '1001';
  let studentName='વિદ્યાર્થી';
  try{
    const students=JSON.parse(localStorage.getItem('schoolStudents')||'[]');
    const found=students.find(s=>s.number===studentNumber);
    if(found) studentName=found.name;
  }catch(error){}
  const result={id:`online-${Date.now()}`,studentNumber,studentName,standard,subject,score,total:questions.length,date:new Date().toLocaleString('gu-IN')};
  const results=JSON.parse(localStorage.getItem('examResults')||'[]');results.unshift(result);localStorage.setItem('examResults',JSON.stringify(results.slice(0,50)));
  $('examArea').classList.add('hidden');$('resultArea').classList.remove('hidden');
  $('scoreText').textContent=`${score} / ${questions.length}`;
  $('scorePercent').textContent=`${Math.round(score/questions.length*100)}%`;
  $('resultMessage').textContent=auto?'સમય પૂરો થયો.':'પરીક્ષા સફળતાપૂર્વક પૂર્ણ થઈ.';
}
